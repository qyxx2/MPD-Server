  await h.wrapper.get(`[data-queue-operation="${operation}"]`).trigger('click')
  const request = h.network.requests[0]!
  expect(new URL(request.url).pathname).toBe('/api/playback/queue/items/duplicate-next')
  expect(request.init?.method).toBe(operation === 'delete' ? 'DELETE' : 'PUT')
