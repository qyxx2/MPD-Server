    expect(h.store.snapshot!.queue.items.map(i => i.queue_item_id).sort()).toEqual(s.queue.items.map(i => i.queue_item_id).sort())
    expect(h.store.snapshot!.queue.items.find(i => i.queue_item_id === 'duplicate-next')!.position).toBe(operation === 'next' ? 1 : 3)
